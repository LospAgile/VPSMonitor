import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const script = fs.readFileSync(new URL('./provider-augment.js.example', import.meta.url), 'utf8');
let fetches = 0, timerCount = 0;
const base = {status:'ok', timestamp:Math.floor(Date.now()/1000), interval_seconds:60, wan_up:true, dns_ok:null, nps_running:true, wan_outages_24h:0, observation_seconds_24h:120, failed_probes:[]};
const context = vm.createContext({Date, AbortController, setTimeout:(fn,t)=>{timerCount++;return setTimeout(fn,t);}, clearTimeout:id=>{timerCount--;clearTimeout(id);}, fetch: async ()=>{fetches++;return {ok:true,json:async()=>({nodes:{'router-a':{...base,name:'Router <A>'},'router-b':{...base,name:'B'}}})};}});
vm.runInContext(script, context);
const original = '<b>Original alert</b>';
assert.equal(await context.augmentEvent({event:'Login',clients:[{uuid:'router-a'}]},original), original);
assert.equal(fetches,0);
const result = await context.augmentEvent({event:'Offline',clients:[{uuid:'router-a',name:'Router A'}]},original);
assert.ok(result.startsWith(original));
assert.ok(result.includes('Router &lt;A&gt;'));
assert.ok(!result.includes('B（'));
assert.ok(result.includes('DNS 未知'));
assert.ok(result.includes('实际观测0小时2分'));
const vps = await context.augmentEvent({event:'Online',clients:[{uuid:'vps-1',name:'VPS'}]},original);
assert.ok(vps.includes('B（'));
context.fetch = async ()=>({ok:true,json:async()=>({nodes:{'router-a':{...base,name:'A',degraded_probes:[{label:'VPS <partial>',loss_percent:50}]}}})});
const degraded = await context.augmentEvent({event:'Offline',clients:[{uuid:'router-a'}]},original);
assert.ok(degraded.includes('部分丢包：VPS &lt;partial&gt; 50%'));
assert.ok(degraded.includes('本轮 ICMP 样本'));
assert.ok(!degraded.includes('未通过：'));
context.fetch = async ()=>({ok:true,json:async()=>({nodes:{'router-a':{name:'A',status:'unavailable',last_sample:{...base,timestamp:base.timestamp-400}}}})});
assert.ok((await context.augmentEvent({event:'Offline',clients:[{uuid:'router-a'}]},original)).includes('最后样本，当前状态未知'));
context.fetch = async ()=>{throw Error('cache unavailable');};
assert.equal(await context.augmentEvent({event:'Offline',clients:[{uuid:'router-a'}]},original),original);
context.fetch = (_,opts)=>new Promise((_,reject)=>opts.signal.addEventListener('abort',()=>reject(Error('aborted'))));
const started=Date.now();
assert.equal(await context.augmentEvent({event:'Offline',clients:[{uuid:'router-a'}]},original),original);
assert.ok(Date.now()-started>=1900 && Date.now()-started<3000);
assert.equal(timerCount,0);
console.log('Provider: event mapping, escaping, partial loss, historical samples, coverage, failure and 2s timeout passed.');
